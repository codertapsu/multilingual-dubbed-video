#!/usr/bin/env node
/**
 * scripts/check-versions.mjs — assert the five places that carry the app version
 * agree, and optionally set them all in one reviewable command.
 *
 * The version lives in four manifests plus Cargo.lock, and until now they were
 * kept in sync entirely by hand, under release pressure, with the only
 * enforcement being prose in docs/RELEASING.md ("review each — don't blind-sed").
 * Tauri reads tauri.conf.json for the bundle and the updater comparison, so a
 * missed bump elsewhere does not break a release — it just makes the repo lie
 * about what it is, which is how the next person mis-diagnoses a version bug.
 *
 * Usage:
 *   node scripts/check-versions.mjs            # verify; exit 1 on disagreement
 *   node scripts/check-versions.mjs --set 0.9.1
 *
 * --set rewrites the four manifests in place. It deliberately does NOT touch
 * Cargo.lock: that is regenerated by the next `cargo`/`tauri build`, and hand-
 * editing a lockfile is how you get a lockfile that disagrees with itself. The
 * check reports a stale Cargo.lock as a warning for that reason.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Each source: how to read the version out, and how to write a new one back. */
const SOURCES = [
  {
    file: 'package.json',
    read: (t) => JSON.parse(t).version,
    // Anchor on the FIRST "version" key so a dependency's version is never hit.
    write: (t, v) => t.replace(/("version"\s*:\s*")[^"]+(")/, `$1${v}$2`),
  },
  {
    file: 'apps/desktop/package.json',
    read: (t) => JSON.parse(t).version,
    write: (t, v) => t.replace(/("version"\s*:\s*")[^"]+(")/, `$1${v}$2`),
  },
  {
    file: 'apps/desktop/src-tauri/tauri.conf.json',
    read: (t) => JSON.parse(t).version,
    write: (t, v) => t.replace(/("version"\s*:\s*")[^"]+(")/, `$1${v}$2`),
  },
  {
    file: 'apps/desktop/src-tauri/Cargo.toml',
    // [package] version — the first bare `version = "..."` in the file.
    read: (t) => /^\s*version\s*=\s*"([^"]+)"/m.exec(t)?.[1],
    write: (t, v) => t.replace(/^(\s*version\s*=\s*")[^"]+(")/m, `$1${v}$2`),
  },
];

/** Cargo.lock's own entry for the desktop crate — read-only (cargo owns it). */
const CARGO_LOCK = 'apps/desktop/src-tauri/Cargo.lock';
const CRATE = 'videodubber-desktop';

function readLockVersion() {
  let text;
  try {
    text = readFileSync(path.join(ROOT, CARGO_LOCK), 'utf8');
  } catch {
    return undefined;
  }
  // [[package]] blocks are `name = "..."` then `version = "..."`.
  const m = new RegExp(`name\\s*=\\s*"${CRATE}"\\s*\\nversion\\s*=\\s*"([^"]+)"`).exec(text);
  return m?.[1];
}

/** Read every source. Exported for tests. */
export function readVersions() {
  return SOURCES.map((s) => {
    const text = readFileSync(path.join(ROOT, s.file), 'utf8');
    return { file: s.file, version: s.read(text) };
  });
}

function main() {
  const setIdx = process.argv.indexOf('--set');
  const target = setIdx === -1 ? undefined : process.argv[setIdx + 1];

  if (target !== undefined) {
    if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(target)) {
      console.error(`check-versions: "${target}" is not a semver version.`);
      process.exit(1);
    }
    for (const s of SOURCES) {
      const p = path.join(ROOT, s.file);
      const text = readFileSync(p, 'utf8');
      const next = s.write(text, target);
      // Read the result back with the SAME reader the check uses, and refuse to
      // report success unless it agrees. Each `write` is a regex on the first
      // `version` key, so a reordered manifest (or a new top-level `"version"`
      // above the package's own) would leave the file untouched — or rewrite the
      // wrong key — while this loop still printed "set ... -> X.Y.Z". A bump that
      // lies is worse than a bump that fails: the next `check` run is the only
      // thing that would have caught it, and by then the commit is written.
      const after = s.read(next);
      if (after !== target) {
        console.error(
          `check-versions: could not set the version in ${s.file} ` +
            `(it still reads ${after ?? '(unreadable)'}). Edit it by hand.`,
        );
        process.exit(1);
      }
      if (next !== text) writeFileSync(p, next);
      console.log(`  set ${s.file} -> ${target}`);
    }
    console.log(
      `\nNow run a build (or \`cargo update -p ${CRATE}\`) so ${CARGO_LOCK} follows, then commit all five.`,
    );
    return;
  }

  const found = readVersions();
  const missing = found.filter((f) => !f.version);
  const distinct = [...new Set(found.map((f) => f.version))];

  if (missing.length || distinct.length > 1) {
    console.error('check-versions: the app version disagrees across manifests:');
    for (const f of found) console.error(`  ${f.version ?? '(unreadable)'}  ${f.file}`);
    console.error('\nFix with:  node scripts/check-versions.mjs --set <X.Y.Z>');
    process.exit(1);
  }

  const version = distinct[0];
  const lock = readLockVersion();
  if (lock && lock !== version) {
    // A warning, not an error: Cargo.lock catches up on the next build, and
    // failing the release for it would be failing on a derived file.
    console.warn(
      `check-versions: WARNING ${CARGO_LOCK} still says ${CRATE} ${lock} (manifests say ${version}).\n` +
        '  It will be rewritten by the next cargo/tauri build — commit it with the bump.',
    );
  }
  console.log(`check-versions: OK — all manifests at ${version}${lock ? ` (Cargo.lock ${lock})` : ''}.`);
}

// Only run when invoked directly, so a test can import readVersions().
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
