/** Inputs needed to construct the ffmpeg argv (already-validated paths). */
export interface RenderArgsContext {
  inputVideoPath: string;
  audioPath: string;
  outputPath: string;
  subtitleExportMode: SubtitleExportMode;
  /** Path to the subtitle to embed/burn (required for embedded-soft/burned-in). */
  subtitlePath?: string;
  /** force_style for a burned .srt (renderFinalVideo burns a styled .ass instead). */
  burnSubtitleStyle?: SubtitleStyle;
  copyVideoStream?: boolean;
  /** Platform override for subtitle path escaping (tests). */
  platform?: NodeJS.Platform;
  /** Video encoder for the burned-in re-encode (default libx264). */
  videoCodec?: string;
  /** Encoder-specific args (preset/crf for x264, cq/q for hardware). */
  videoCodecArgs?: string[];
  /** Fonts directory handed to libass for the burn (the bundled subtitle font). */
  fontsDir?: string;
}

const AUDIO_ARGS = ['-c:a', 'aac', '-b:a', '192k'] as const;

/**
 * A machine-readable mark that the dub's speech is AI-generated, in every
 * render. Every voice VideoDubber speaks with is synthetic, cloned voices
 * included; Vietnam's AI law (in force since 2026-03-01) and the EU AI Act ask
 * for such a mark on synthetic audio, and the voice licences (VieNeu,
 * Supertonic's OpenRAIL-M, ZeroTTS) ask users to disclose it. MP4 stores it as
 * the comment atom; ffprobe shows it under format tags.
 */
export const AI_SPEECH_METADATA = [
  '-metadata',
  'comment=The speech in this video was generated by AI (VideoDubber).',
] as const;

/**
 * Build the ffmpeg argv array for a render. Pure function.
 * Throws TTS_VOICE_MISSING-adjacent config errors? No — it validates that a
 * subtitle path is present when the mode requires one (UNSUPPORTED_MEDIA is the
 * wrong code; we use UNKNOWN with a clear remediation, surfaced before spawn).
 */
export function buildRenderArgs(ctx: RenderArgsContext): string[] {
  const {
    inputVideoPath,
    audioPath,
    outputPath,
    subtitleExportMode,
    subtitlePath,
    burnSubtitleStyle,
    platform,
  } = ctx;
  const copyVideo = ctx.copyVideoStream !== false; // default true except burned-in
  // Encoder for re-encodes: software x264 unless the caller resolved another
  // (renderQuality "fast"/"auto" with a probed hardware encoder).
  const videoCodec = ctx.videoCodec ?? LIBX264.codec;
  const videoCodecArgs = ctx.videoCodecArgs ?? LIBX264.args;

  switch (subtitleExportMode) {
    case 'burned-in': {
      if (!subtitlePath) {
        throw missingSubtitle('burned-in');
      }
      // Burning requires a video re-encode; -c:v copy is impossible here.
      const filter = buildSubtitlesFilter(subtitlePath, burnSubtitleStyle, platform, ctx.fontsDir);
      return [
        '-y',
        '-i',
        inputVideoPath,
        '-i',
        audioPath,
        '-map',
        '0:v:0',
        '-map',
        '1:a:0',
        '-vf',
        filter,
        '-c:v',
        videoCodec,
        ...videoCodecArgs,
        ...AUDIO_ARGS,
        ...AI_SPEECH_METADATA,
        outputPath,
      ];
    }

    case 'embedded-soft': {
      if (!subtitlePath) {
        throw missingSubtitle('embedded-soft');
      }
      // Soft subtitle stream muxed in as mov_text (mp4-compatible).
      return [
        '-y',
        '-i',
        inputVideoPath,
        '-i',
        audioPath,
        '-i',
        subtitlePath,
        '-map',
        '0:v:0',
        '-map',
        '1:a:0',
        '-map',
        '2:0',
        '-c:v',
        copyVideo ? 'copy' : 'libx264',
        ...AUDIO_ARGS,
        '-c:s',
        'mov_text',
        ...AI_SPEECH_METADATA,
        outputPath,
      ];
    }

    case 'none':
    case 'srt-file':
    case 'vtt-file':
    default: {
      // No subtitle inside the container; sidecar (if any) is copied separately.
      return [
        '-y',
        '-i',
        inputVideoPath,
        '-i',
        audioPath,
        '-map',
        '0:v:0',
        '-map',
        '1:a:0',
        '-c:v',
        copyVideo ? 'copy' : 'libx264',
        ...AUDIO_ARGS,
        ...AI_SPEECH_METADATA,
        outputPath,
      ];
    }
  }
}

function missingSubtitle(mode: SubtitleExportMode): AppErrorException {
  return new AppErrorException({
    code: 'UNKNOWN',
    message: `subtitleExportMode "${mode}" requires a subtitlePath, but none was provided.`,
    remediation: 'Generate translated subtitles before rendering, or use mode "none".',
    docsRef: 'docs/TROUBLESHOOTING.md#subtitles',
  });
}

/**
 * Compute the sidecar destination path next to the output video for srt/vtt
 * file modes: <outputBasename>.srt / .vtt. Pure helper.
 */
export function sidecarDestinationPath(
  outputPath: string,
  mode: SubtitleExportMode,
): string | undefined {
  if (mode !== 'srt-file' && mode !== 'vtt-file') return undefined;
  const dir = dirname(outputPath);
  const base = basename(outputPath, extname(outputPath));
  const ext = mode === 'srt-file' ? '.srt' : '.vtt';
  return join(dir, `${base}${ext}`);
}

/** The shared render input plus what only the media worker needs. */
export interface RenderFinalVideoOptions extends RenderFinalVideoInput {
  /**
   * Fonts directory for burned-in subtitles: the app's bundled fonts. When
   * absent: VIDEODUBBER_FONTS_DIR, then this package's assets/fonts (dev).
   */
  fontsDir?: string;
}

/** Injectable seams for {@link renderFinalVideo} (tests, diagnostics). */
export interface RenderDeps {
  /** Hardware-encoder probe. Default: the per-process cached real probe. */
  probeHardwareEncoder?: () => Promise<HardwareEncoderProbe>;
}

/** The shared result plus how the media worker produced it. */
export interface RenderFinalVideoReport extends RenderFinalVideoResult {
  /**
   * Burned-in only: which encoder made the video stream (and whether a
   * hardware failure handed it to x264), plus what the probe saw. Chosen at
   * runtime per machine, so this is the only record of it — log it.
   */
  videoEncoder?: VideoEncodeReport & { probe?: EncoderProbeAttempt[] };
  /**
   * Burned-in only: the subtitle font asked for and the fonts dir libass got.
   * `Arial` without the bundled family means the bundled font was not
   * reachable (the packaged fonts dir is missing) — log it.
   */
  burnFont?: BurnFont;
}

/** Render the final video and report duration + any sidecar subtitle paths. */
export async function renderFinalVideo(
  input: RenderFinalVideoOptions,
  runOpts: RunOptions = {},
  deps: RenderDeps = {},
): Promise<RenderFinalVideoReport> {
  assertInputReadable(input.inputVideoPath);
  assertInputReadable(input.audioPath);
  assertOutputWritable(input.outputPath);

  // A logo, a part's window or its opening and closing: the picture is
  // re-encoded through one filtergraph (overlay.ts), whatever the subtitle mode.
  if (input.logo || input.range || input.effects) return renderFiltered(input, runOpts, deps);

  // Burned-in subtitles use the libavfilter "subtitles" filter, which is only
  // present in an FFmpeg built with libass. Detect a missing filter up front so
  // we fail with a clear, actionable error instead of an opaque ffmpeg exit code.
  if (input.subtitleExportMode === 'burned-in') {
    if (!(await ffmpegHasFilter('subtitles', runOpts))) {
      throw new AppErrorException({
        code: 'FFMPEG_FILTER_MISSING',
        message:
          'Burned-in subtitles require an FFmpeg built with libass (the "subtitles" filter), which this FFmpeg lacks.',
        remediation:
          'Install an FFmpeg built with libass (macOS: `brew install ffmpeg-full`, then set FFMPEG_PATH/FFPROBE_PATH to it), or choose a different subtitle mode (embedded-soft / srt-file / vtt-file).',
        docsRef: 'docs/TROUBLESHOOTING.md#ffmpeg-filter-missing',
      });
    }
  }

  if (
    (input.subtitleExportMode === 'embedded-soft' ||
      input.subtitleExportMode === 'burned-in' ||
      input.subtitleExportMode === 'srt-file' ||
      input.subtitleExportMode === 'vtt-file') &&
    input.subtitlePath
  ) {
    assertInputReadable(input.subtitlePath);
  }

  if (input.subtitleExportMode === 'burned-in') {
    const { videoEncoder, burnFont } = await renderBurnedIn(input, runOpts, deps);
    return {
      outputPath: input.outputPath,
      durationMs: await probeDurationMs(input.outputPath),
      sidecarSubtitlePaths: [],
      videoEncoder,
      burnFont,
    };
  }

  // Atomic: a killed render (cancel, crash, disk full) leaves a non-empty mp4
  // with no moov atom — unplayable, yet non-empty, which is all the pipeline's
  // resume check looks at, so the next run would "skip" Render and hand the user
  // a broken file as a success. The `.partial` keeps the `.mp4` extension so
  // ffmpeg still infers the mp4 muxer from it.
  await writeAtomically(input.outputPath, (partial) => {
    const args = buildRenderArgs({
      inputVideoPath: input.inputVideoPath,
      audioPath: input.audioPath,
      outputPath: partial,
      subtitleExportMode: input.subtitleExportMode,
      subtitlePath: input.subtitlePath,
      copyVideoStream: input.copyVideoStream,
    });
    return runFfmpeg(args, runOpts);
  });

  const sidecarSubtitlePaths = copySidecar(input);
  const durationMs = await probeDurationMs(input.outputPath);

  return {
    outputPath: input.outputPath,
    durationMs,
    sidecarSubtitlePaths,
  };
}

/** Copy the sidecar subtitle next to the output for srt-file / vtt-file modes. */
function copySidecar(input: RenderFinalVideoOptions): string[] {
  const sidecarDest = sidecarDestinationPath(input.outputPath, input.subtitleExportMode);
  if (!sidecarDest || !input.subtitlePath) return [];
  assertInputReadable(input.subtitlePath);
  copyFileSync(input.subtitlePath, sidecarDest);
  return [sidecarDest];
}

/**
 * The styled ASS script a burned-in render draws (or the subtitle itself when
 * it already is one), on the video's pixel grid.
 */
function writeBurnScript(
  input: RenderFinalVideoOptions,
  subtitlePath: string,
  burnFont: BurnFont,
  geometry: Pick<VideoGeometry, 'width' | 'height'>,
  durationMs: number,
  scratch: string,
): string {
  if (isAssScript(subtitlePath)) return subtitlePath;
  const cues = parseSubtitleCues(readFileSync(subtitlePath, 'utf8'));
  const style = { ...input.burnSubtitleStyle, fontFamily: burnFont.family };
  const layout = computeAssLayout(style, geometry.width, geometry.height);
  // The band spans the whole video; a little past the container duration
  // covers streams that run slightly long. Unknown duration: the ASS max.
  const endMs = durationMs > 0 ? durationMs + 1000 : Number.MAX_SAFE_INTEGER;
  const scriptPath = join(scratch, 'burn.ass');
  writeFileSync(scriptPath, buildAssDocument(cues, layout, endMs), 'utf8');
  return scriptPath;
}

/**
 * A render with a logo, a part's window, or its opening and closing: one
 * re-encode through overlay.ts's filtergraph, with the encoder (and its x264
 * retry) burned-in renders use. Subtitles still follow the mode: burned into
 * the picture, embedded as a soft track, or written beside the video.
 */
async function renderFiltered(
  input: RenderFinalVideoOptions,
  runOpts: RunOptions,
  deps: RenderDeps,
): Promise<RenderFinalVideoReport> {
  const burning = input.subtitleExportMode === 'burned-in';
  const cards = input.effects?.cards?.filter((c) => c.text.trim() && c.endMs > c.startMs) ?? [];
  if ((burning || cards.length > 0) && !(await ffmpegHasFilter('subtitles', runOpts))) {
    throw new AppErrorException({
      code: 'FFMPEG_FILTER_MISSING',
      message: 'Drawing text on the video requires an FFmpeg built with libass (the "subtitles" filter), which this FFmpeg lacks.',
      remediation:
        'Install an FFmpeg built with libass (macOS: `brew install ffmpeg-full`, then set FFMPEG_PATH/FFPROBE_PATH to it), or choose a non-burned subtitle mode.',
      docsRef: 'docs/TROUBLESHOOTING.md#ffmpeg-filter-missing',
    });
  }
  if (burning && !input.subtitlePath) throw missingSubtitle('burned-in');
  if (input.subtitleExportMode === 'embedded-soft' && !input.subtitlePath) throw missingSubtitle('embedded-soft');
  if (input.subtitlePath) assertInputReadable(input.subtitlePath);
  if (input.logo) assertInputReadable(input.logo.imagePath);

  const geometry = await probeVideoGeometry(input.inputVideoPath, runOpts);
  const durationMs = input.range ? input.range.endMs - input.range.startMs : geometry.durationMs;
  const burnFont = chooseBurnFont(resolveFontsDir(input.fontsDir), input.burnSubtitleStyle?.fontFamily);
  const scratch = mkdtempSync(join(tmpdir(), 'vd-render-'));
  try {
    const burnScriptPath = burning ? writeBurnScript(input, input.subtitlePath!, burnFont, geometry, durationMs, scratch) : undefined;
    let cardsScriptPath: string | undefined;
    if (cards.length > 0) {
      cardsScriptPath = join(scratch, 'cards.ass');
      writeFileSync(cardsScriptPath, buildCardsAss(cards, geometry.width, geometry.height, burnFont.family), 'utf8');
    }
    const probe = wantsHardwareEncoder(input.renderQuality)
      ? await (deps.probeHardwareEncoder ?? cachedHardwareEncoderProbe)()
      : undefined;
    const plan = planVideoEncode(input.renderQuality, probe, geometry);
    const { report } = await encodeWithFallback(
      plan,
      (encoder) =>
        writeAtomically(input.outputPath, (partial) =>
          runFfmpeg(
            buildFilteredRenderArgs({
              inputVideoPath: input.inputVideoPath,
              audioPath: input.audioPath,
              outputPath: partial,
              mode: input.subtitleExportMode,
              ...(burnScriptPath ? { burnScriptPath } : {}),
              ...(input.subtitleExportMode === 'embedded-soft' && input.subtitlePath ? { softSubtitlePath: input.subtitlePath } : {}),
              ...(burnFont.fontsDir ? { fontsDir: burnFont.fontsDir } : {}),
              width: geometry.width,
              height: geometry.height,
              durationMs,
              ...(input.logo ? { logo: input.logo } : {}),
              ...(input.range ? { range: input.range } : {}),
              ...(input.effects ? { effects: input.effects } : {}),
              ...(cardsScriptPath ? { cardsScriptPath } : {}),
              videoCodec: encoder.codec,
              videoCodecArgs: encoder.args,
              audioArgs: AUDIO_ARGS,
              metadataArgs: AI_SPEECH_METADATA,
            }),
            runOpts,
          ),
        ),
      runOpts.signal,
    );
    return {
      outputPath: input.outputPath,
      durationMs: await probeDurationMs(input.outputPath),
      sidecarSubtitlePaths: copySidecar(input),
      videoEncoder: { ...report, ...(probe ? { probe: probe.attempts } : {}) },
      burnFont,
    };
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

/** True for a subtitle that already is an ASS/SSA script (burned as-is). */
function isAssScript(path: string): boolean {
  return /\.(ass|ssa)$/i.test(path);
}

/**
 * The burned-in re-encode: generate the styled ASS script, pick the encoder,
 * encode — through writeAtomically on EVERY attempt, so a hardware try that dies
 * halfway leaves no partial behind and the x264 retry starts clean.
 */
async function renderBurnedIn(
  input: RenderFinalVideoOptions,
  runOpts: RunOptions,
  deps: RenderDeps,
): Promise<{ videoEncoder: VideoEncodeReport & { probe?: EncoderProbeAttempt[] }; burnFont: BurnFont }> {
  const subtitlePath = input.subtitlePath;
  if (!subtitlePath) throw missingSubtitle('burned-in');

  const geometry = await probeVideoGeometry(input.inputVideoPath, runOpts);
  const burnFont = chooseBurnFont(resolveFontsDir(input.fontsDir), input.burnSubtitleStyle?.fontFamily);
  const fontsDir = burnFont.fontsDir;
  const scratch = mkdtempSync(join(tmpdir(), 'vd-burn-'));
  try {
    const scriptPath = writeBurnScript(input, subtitlePath, burnFont, geometry, geometry.durationMs, scratch);

    const probe = wantsHardwareEncoder(input.renderQuality)
      ? await (deps.probeHardwareEncoder ?? cachedHardwareEncoderProbe)()
      : undefined;
    const plan = planVideoEncode(input.renderQuality, probe, geometry);

    const { report } = await encodeWithFallback(
      plan,
      (encoder) =>
        writeAtomically(input.outputPath, (partial) =>
          runFfmpeg(
            buildRenderArgs({
              inputVideoPath: input.inputVideoPath,
              audioPath: input.audioPath,
              outputPath: partial,
              subtitleExportMode: 'burned-in',
              subtitlePath: scriptPath,
              copyVideoStream: false,
              videoCodec: encoder.codec,
              videoCodecArgs: encoder.args,
              ...(fontsDir ? { fontsDir } : {}),
            }),
            runOpts,
          ),
        ),
      runOpts.signal,
    );
    return { videoEncoder: { ...report, ...(probe ? { probe: probe.attempts } : {}) }, burnFont };
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}
